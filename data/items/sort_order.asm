ItemSortRanks:
	table_width 1
	for item_id, 256
		if DEF(_BagSortRank_{d:item_id})
			db _BagSortRank_{d:item_id}
			PURGE _BagSortRank_{d:item_id}
		else
			db $ff
		endc
	endr
	assert_table_length 256

